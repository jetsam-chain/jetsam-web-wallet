import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { encodeQr, qrPenalty } from "../js/qr.js";

const ref = JSON.parse(readFileSync(new URL("./fixtures/qr-reference.json", import.meta.url), "utf8"));
const toRows = (m) => m.modules.map((row) => row.map((d) => (d ? "1" : "0")).join(""));

test("reference fixture is present (generated by tools/gen_qr_reference.py)", () => {
  assert.ok(ref.cases.length >= 200);
});

test("every fixed-mask symbol matches the independent Python encoder module for module", () => {
  for (const c of ref.cases.filter((c) => c.mask !== null)) {
    const m = encodeQr(c.text, { level: c.level, mask: c.mask });
    const label = `${c.level}/mask ${c.mask}/${c.text.slice(0, 12)}`;
    assert.equal(m.version, c.version, label + " version");
    assert.equal(m.size, 17 + 4 * c.version, label + " size");
    assert.deepEqual(toRows(m), c.rows, label);
  }
});

test("automatic mask: the chosen symbol has the lowest penalty of the eight", () => {
  for (const c of ref.cases.filter((c) => c.mask === null)) {
    const auto = encodeQr(c.text, { level: c.level });
    const scores = [];
    for (let k = 0; k < 8; k++) scores.push(qrPenalty(encodeQr(c.text, { level: c.level, mask: k }).modules));
    assert.equal(qrPenalty(auto.modules), Math.min(...scores), c.level + "/" + c.text.slice(0, 12));
  }
});

test("an address fits a small symbol at level M", () => {
  const m = encodeQr("j1wl99gzalncqhk052zw07jymxh5qdhr9q2xx3zwjzqeny620sgncqkfyv2z", { level: "M" });
  assert.equal(m.version, 4);
  assert.equal(m.size, 33);
});

test("non-ASCII text is encoded as UTF-8 bytes", () => {
  const m = encodeQr("µJTM", { level: "M", mask: 0 });
  assert.equal(m.version, 1);
});

test("too much data is refused rather than truncated", () => {
  assert.throws(() => encodeQr("x".repeat(5000), { level: "M" }), RangeError);
});
